from datetime import timedelta
from django.core.exceptions import ValidationError
from django.db import models
from django.utils import timezone

class RecordServer(models.Model):
    """
    Represents the physical or virtual machines handling the recording process.
    """
    name = models.CharField(max_length=100, help_text="Recorder Name (e.g., Rec-Srv-01)")
    ip_address = models.GenericIPAddressField()
    storage_path = models.CharField(max_length=500, help_text="Base directory for recordings")
    is_active = models.BooleanField(default=True)

    def __str__(self):
        return f"{self.name} ({self.ip_address})"

    class Meta:
        verbose_name = "Record Server"
        verbose_name_plural = "Record Servers"


class RecordPort(models.Model):
    """
    Represents a specific recording 'engine', 'channel', or physical input (e.g., DeckLink port) on a server.
    """
    server = models.ForeignKey(
        RecordServer, 
        on_delete=models.CASCADE, 
        related_name='ports'
    )
    channel_index = models.IntegerField(help_text="The internal ID of the recorder instance")
    name = models.CharField(max_length=100, help_text="e.g., DeckLink Input 1 / High-Res Master Rec")
    
    # Track what is currently happening on this port (source removed as requested)
    is_recording = models.BooleanField(default=False)

    def __str__(self):
        return f"{self.server.name} - Port {self.channel_index} ({self.name})"

    class Meta:
        unique_together = ['server', 'channel_index']


class Recording(models.Model):
    """
    Represents a captured file record generated by a specific port.
    """
    STATUS_CHOICES = [
        ('SCHEDULED', 'Scheduled'),
        ('RECORDING', 'Recording'),
        ('COMPLETED', 'Completed'),
        ('FAILED', 'Failed'),
        ('STOPPED', 'Manually Stopped'),
    ]

    port = models.ForeignKey(
        RecordPort,
        on_delete=models.SET_NULL,
        null=True,
        related_name='recordings'
    )
    filename = models.CharField(max_length=255)
    filepath = models.CharField(max_length=1000, help_text="Absolute file system path to the recording file")
    
    start_time = models.DateTimeField(default=timezone.now)
    end_time = models.DateTimeField(null=True, blank=True)
    
    file_size = models.BigIntegerField(default=0, help_text="Size in bytes")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='SCHEDULED')
    note = models.TextField(blank=True, default='', help_text="Operator note")

    @property
    def duration(self):
        if self.end_time:
            # Handle edge case where end_time might accidentally be before start_time
            if self.end_time < self.start_time:
                return timedelta(0)
            return self.end_time - self.start_time
        
        now = timezone.now()
        if self.start_time > now:
            return timedelta(0)  # Safe default if scheduled for the future
        return now - self.start_time

    def clean(self):
        super().clean()
        
        # Validation logic for start_time and end_time
        if self.start_time and self.end_time:
            if self.end_time < self.start_time + timedelta(seconds=10):
                raise ValidationError({
                    'end_time': "The end time must be at least 10 seconds after the start time."
                })

    def save(self, *args, **kwargs):
        # Force validation to run before saving (Django doesn't call clean() automatically on save())
        self.full_clean()
        super().save(*args, **kwargs)

    def __str__(self):
        return f"{self.filename} ({self.status})"

    class Meta:
        ordering = ['-start_time']

class RecordingSetting(models.Model):
    default_duration_minutes = models.PositiveIntegerField(default=30)

    class Meta:
        verbose_name = "Recording Setting"
        verbose_name_plural = "Recording Settings"

    def __str__(self):
        return f"Default duration: {self.default_duration_minutes} min"


class RecordLog(models.Model):
    """
    Audit trail and system events for recordings (e.g., errors, state changes).
    """
    recording = models.ForeignKey(
        Recording, 
        on_delete=models.CASCADE, 
        related_name='logs',
        null=True,
        blank=True
    )
    timestamp = models.DateTimeField(default=timezone.now)
    
    # Adding a default or allowing blank lets existing database rows pass safely
    event_type = models.CharField(
        max_length=50, 
        default='SYSTEM', 
        help_text="e.g., START, STOP, ERROR, CHOP"
    )
    message = models.TextField(
        blank=True, 
        default='', 
        help_text="Detailed logs or error messages from the capture engine"
    )

    def __str__(self):
        return f"[{self.timestamp}] {self.event_type} - Recording ID: {self.recording_id}"

    class Meta:
        ordering = ['-timestamp']